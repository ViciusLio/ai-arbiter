"""The compliance commands end to end. Synchronous: the CLI runs its own event loop."""

import re
import sqlite3
from pathlib import Path

from typer.testing import CliRunner

from ai_arbiter.cli.main import app

runner = CliRunner()
EXAMPLES = str(Path(__file__).parents[2] / "examples" / "systems.yaml")


def arbiter(*arguments: str, ok: bool = True) -> str:
    result = runner.invoke(app, list(arguments))
    assert (result.exit_code == 0) is ok, result.output
    return result.output


def workspace() -> None:
    arbiter("init")
    arbiter("systems", "apply", "-f", EXAMPLES)


def finding_id(rule_text: str, system: str) -> str:
    for line in arbiter("findings", "list").splitlines():
        if rule_text in line and system in line:
            return line.split()[0]
    raise AssertionError(f"no finding '{rule_text}' for {system}")


def test_apply_declares_and_classifies_the_example_systems() -> None:
    arbiter("init")

    first = arbiter("systems", "apply", "-f", EXAMPLES)
    again = arbiter("systems", "apply", "-f", EXAMPLES)

    assert re.search(r"cv-screening\s+created\s+high_risk", first)
    assert re.search(r"call-centre-mood-monitor\s+created\s+prohibited", first)
    assert re.search(r"marketing-copy-generator\s+created\s+undetermined", first)
    assert "indicative until a person reviews them" in first
    assert re.search(r"cv-screening\s+unchanged\s+high_risk", again)


