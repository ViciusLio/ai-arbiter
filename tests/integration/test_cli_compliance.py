def test_scan_then_review_a_finding_through_its_lifecycle() -> None:
    workspace()

    scanned = arbiter("scan")
    listed = arbiter("findings", "list")
    reference = finding_id("no reference to the provider", "loan-pre-screening")
    shown = arbiter("findings", "show", reference)
    confirmed = arbiter("findings", "review", reference, "--to", "confirmed", "--reviewer", "Ada")
    refused = arbiter(
        "findings", "review", reference, "--to", "false_positive", "--reviewer", "Ada", ok=False
    )
    history = arbiter("findings", "show", reference)

    assert "Scanned 7 systems:" in scanned
    assert "proposals until a person reviews them" in scanned
    assert listed.index("Critical") < listed.index("Low")
    assert "rule:      SCAN-DEROGATION-WITHOUT-ASSESSMENT" in shown
    assert "reference: EU-AI-ACT 6(4)" in shown
    assert "system_key: loan-pre-screening" in shown
    assert f"{reference}: confirmed by Ada" in confirmed
    assert "Error: a finding that is confirmed cannot become false_positive" in refused
    assert "open -> confirmed by a reviewer" in history


def test_a_false_positive_with_a_suppression_and_an_accepted_risk() -> None:
    workspace()
    arbiter("scan")
    owner = finding_id("No owner is named", "cv-screening")
    oversight = finding_id("human oversight", "cv-screening")

    rejected = arbiter(
        "findings",
        "review",
        owner,
        "--to",
        "false_positive",
        "--reviewer",
        "Ada",
        "--reason",
        "Ownership is tracked in the CMDB.",
        "--suppress",
        "rule",
    )
    accepted = arbiter(
        "findings",
        "review",
        oversight,
        "--to",
        "accepted",
        "--reviewer",
        "Ada",
        "--reason",
        "Oversight roles are assigned in Q1.",
        "--until",
        "2099-01-01",
    )
    rescanned = arbiter("scan")
    active = arbiter("findings", "list")
    everything = arbiter("findings", "list", "--all")

    assert "false_positive by Ada" in rejected
    assert "accepted by Ada" in accepted
    assert "suppressed: 7" in rescanned
    assert "No owner is named" not in active
    assert "accepted" in everything
    assert "Error: finding 'zzzzzzzz' not found" in arbiter(
        "findings", "show", "zzzzzzzz", ok=False
    )


