def test_a_review_is_recorded_under_the_reviewer_and_the_name_stays_out_of_the_audit_log(
    tmp_path: Path,
) -> None:
    workspace()

    confirmed = arbiter(
        "systems", "review", "cv-screening", "--confirm", "--reviewer", "Ada Lovelace"
    )
    overridden = arbiter(
        "systems",
        "review",
        "loan-pre-screening",
        "--override",
        "high_risk",
        "--reason",
        "The provider's assessment does not cover our use.",
        "--reviewer",
        "Ada Lovelace",
    )
    shown = arbiter("systems", "show", "loan-pre-screening")

    assert "cv-screening: high_risk, confirmed by Ada Lovelace" in confirmed
    assert "loan-pre-screening: high_risk, overridden by Ada Lovelace" in overridden
    assert "Tier: High-risk" in shown
    assert "Review: Set by a reviewer" in shown
    assert "engine: Minimal" in shown
    connection = sqlite3.connect(tmp_path / ".arbiter" / "arbiter.db")
    try:
        principals = connection.execute(
            "SELECT count(*) FROM principal WHERE display_name = 'Ada Lovelace'"
        ).fetchone()
        audit = str(connection.execute("SELECT * FROM audit_entry").fetchall())
    finally:
        connection.close()
    assert principals == (1,)
    assert "Ada Lovelace" not in audit
    assert "classification.confirmed" in audit


