def test_digest_to_standard_output_and_to_files(tmp_path: Path) -> None:
    workspace()
    arbiter("scan")

    printed = arbiter("digest", "run", "--locale", "it")
    written = arbiter(
        "digest", "run", "--locale", "all", "--format", "both", "-o", str(tmp_path / "out")
    )
    files = sorted(path.name for path in (tmp_path / "out").iterdir())

    assert printed.startswith("# Digest giornaliero")
    assert "7 sistemi dichiarati" in printed
    assert written.count("Wrote ") == 4
    assert [name.split(".", 1)[1] for name in files] == ["en.html", "en.md", "it.html", "it.md"]
    html = next((tmp_path / "out").glob("*.en.html")).read_text(encoding="utf-8")
    assert "<h1>Daily digest</h1>" in html
    assert "Error: several outputs need a directory" in arbiter(
        "digest", "run", "--locale", "all", ok=False
    )
    assert "Error: unsupported locale 'fr'" in arbiter("digest", "run", "--locale", "fr", ok=False)
    assert "Error: unsupported format 'pdf'" in arbiter(
        "digest", "run", "--format", "pdf", ok=False
    )


